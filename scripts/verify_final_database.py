import json

games = json.load(open('data/pc_games.json', encoding='utf-8'))
subforums = json.load(open('data/subforums.json', encoding='utf-8'))

total = len(games)
with_desc = sum(1 for g in games if g.get('description'))
with_cover = sum(1 for g in games if g.get('cover'))
with_cover_std = sum(1 for g in games if g.get('cover_standard'))
with_screens = sum(1 for g in games if g.get('screenshots') and len(g['screenshots']) > 0)
with_year = sum(1 for g in games if g.get('year') and g['year'] != 'Unknown')
with_genre = sum(1 for g in games if g.get('genre') and g['genre'] != 'Unknown')
with_dev = sum(1 for g in games if g.get('developer') and g['developer'] != 'Unknown')
with_pub = sum(1 for g in games if g.get('publisher') and g['publisher'] != 'Unknown')
with_ver = sum(1 for g in games if g.get('version') and g['version'] != 'Unknown')
with_steam = sum(1 for g in games if g.get('steam_url'))
with_magnet = sum(1 for g in games if g.get('magnet'))

print(f"=== ИТОГОВАЯ ВЕРИФИКАЦИЯ БАЗЫ pc_games.json ===")
print(f"Всего игр в базе: {total}")
print(f"С описанием (description): {with_desc} / {total} ({with_desc/total*100:.1f}%)")
print(f"С обложкой (cover): {with_cover} / {total} ({with_cover/total*100:.1f}%)")
print(f"Со стандартной обложкой (cover_standard): {with_cover_std} / {total} ({with_cover_std/total*100:.1f}%)")
print(f"Со скриншотами (screenshots): {with_screens} / {total} ({with_screens/total*100:.1f}%)")
print(f"С годом/датой выхода (year): {with_year} / {total} ({with_year/total*100:.1f}%)")
print(f"С жанром (genre): {with_genre} / {total} ({with_genre/total*100:.1f}%)")
print(f"С разработчиком (developer): {with_dev} / {total} ({with_dev/total*100:.1f}%)")
print(f"С издателем (publisher): {with_pub} / {total} ({with_pub/total*100:.1f}%)")
print(f"С версией (version): {with_ver} / {total} ({with_ver/total*100:.1f}%)")
print(f"С прямой ссылкой на Steam (steam_url): {with_steam} / {total} ({with_steam/total*100:.1f}%)")
print(f"С рабочей magnet-ссылкой (magnet): {with_magnet} / {total} ({with_magnet/total*100:.1f}%)")
